#!/usr/bin/env python3
"""Generate res/xml/appfilter.xml (ADW format) for the CEDAR icon pack.

Component sources, highest priority first:
  1. explicit "components" in icons.json (verified against the device with
     `adb shell cmd package query-activities -a android.intent.action.MAIN
      -c android.intent.category.LAUNCHER`)
  2. data/legacy-appfilter.xml, the hand-maintained v1 mappings
  3. Arcticons' appfilter.xml: every component the upstream project maps to a
     drawable we ship (thousands of verified package/activity pairs)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARCTICONS_APPFILTER = os.environ.get(
    "ARCTICONS_APPFILTER",
    os.path.expanduser("~/Projects/arcticons-source/app/src/main/res/xml/appfilter.xml"),
)
ITEM_RE = re.compile(
    r'<item\s+component="ComponentInfo\{([^/}]+)/([^}]+)\}"\s+drawable="([^"]+)"'
)
LEGACY_RE = re.compile(
    r'<item\s+component="ComponentInfo\{([^/}]+)/([^}]+)\}"\s+drawable="([^"]+)"'
)


def parse(path):
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as fh:
        return ITEM_RE.findall(fh.read())


def main():
    with open(os.path.join(ROOT, "icons.json"), encoding="utf-8") as fh:
        spec = json.load(fh)
    icons = spec["icons"]

    by_drawable = {}          # our drawable -> list of "pkg/activity"
    for icon in icons:
        by_drawable[icon["drawable"]] = []

    # 1. explicit
    for icon in icons:
        for comp in icon.get("components", []):
            by_drawable[icon["drawable"]].append(comp.strip().strip("{}"))

    # 2. legacy (only drawables we still ship)
    for pkg, act, drawable in parse(os.path.join(ROOT, "data", "legacy-appfilter.xml")):
        if drawable in by_drawable:
            by_drawable[drawable].append("%s/%s" % (pkg, act))

    # 3. Arcticons
    arcticons = parse(ARCTICONS_APPFILTER)
    if not arcticons:
        print("ERROR: Arcticons appfilter not found at %s" % ARCTICONS_APPFILTER, file=sys.stderr)
        sys.exit(1)
    by_name = {}
    for pkg, act, drawable in arcticons:
        by_name.setdefault(drawable, []).append("%s/%s" % (pkg, act))
    for icon in icons:
        if "arcticons" in icon:
            by_drawable[icon["drawable"]].extend(by_name.get(icon["arcticons"], []))

    # dedupe globally, first mapping wins
    seen = set()
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<resources>',
             '    <!--',
             '      Generated by tools/gen_appfilter.py. Do not hand-edit.',
             '      Glyphs derived from Arcticons (GPL-3.0), https://github.com/Arcticons-Team/Arcticons',
             '    -->']
    total = 0
    for icon in icons:
        entries = []
        for comp in by_drawable[icon["drawable"]]:
            if comp in seen:
                continue
            seen.add(comp)
            entries.append('    <item component="ComponentInfo{%s}" drawable="%s"/>'
                           % (comp, icon["drawable"]))
        if not entries:
            continue
        lines.append("")
        lines.append("    <!-- %s -->" % icon["label"])
        lines.extend(entries)
        total += len(entries)
    lines.append("")
    lines.append("</resources>")
    lines.append("")

    out = os.path.join(ROOT, "res", "xml", "appfilter.xml")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote %s: %d components across %d icons" % (out, total, len(icons)))


if __name__ == "__main__":
    main()
